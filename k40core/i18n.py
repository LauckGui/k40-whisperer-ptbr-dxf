PORTUGUESE = {english: portuguese for portuguese, english in ENGLISH.items()}


def translate_text(text, language="pt-BR"):
    """Translate known UI text while preserving numbers and formatting."""
    if not isinstance(text, str) or not text:
        return text
    if language == "en":
        source, target = ENGLISH, "en"
    else:
        source, target = PORTUGUESE, "pt-BR"

    direct = source.get(text)
    if direct is not None:
        return direct

    translated = text
    # Longer phrases first prevents a short label from breaking a sentence.
    for original in sorted(source, key=len, reverse=True):
        if original in translated:
            translated = translated.replace(original, source[original])
    return translated
